// Runtime validation using chess.js to filter out any broken lines
export const OPENINGS: OpeningItem[] = RAW_OPENINGS.filter((op) => {
  const g = new Chess();
  for (const m of op.moves) {
    try {
      const res = g.move(m);
      if (!res) {
        console.warn(`[Openings Data] Invalid move "${m}" in opening "${op.name}".`);
        return false;
      }
    } catch {
      console.warn(`[Openings Data] Exception validating move "${m}" in "${op.name}".`);
      return false;
    }
  }
  return true;
});

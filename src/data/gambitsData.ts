// Runtime validation using chess.js
export const GAMBITS: OpeningItem[] = RAW_GAMBITS.filter((gbt) => {
  const g = new Chess();
  for (const m of gbt.moves) {
    try {
      const res = g.move(m);
      if (!res) {
        console.warn(`[Gambits Data] Invalid move "${m}" in gambit "${gbt.name}".`);
        return false;
      }
    } catch {
      console.warn(`[Gambits Data] Exception validating move "${m}" in "${gbt.name}".`);
      return false;
    }
  }
  return true;
});
